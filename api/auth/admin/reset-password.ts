import crypto from 'crypto';
import { verifySessionToken, parseCookies, validateCsrf } from '../../lib/auth';
import { hashPassword } from '../../lib/hash';
import { getSupabaseServerClient } from '../../lib/supabaseServer';

export default async function handler(req: any, res: any) {
  res.setHeader('Access-Control-Allow-Origin', req.headers?.origin || '*');
  res.setHeader('Access-Control-Allow-Credentials', 'true');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization, X-CSRF-Token');

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ success: false, error: 'Method not allowed. Hanya POST yang didukung.' });
  }

  // 1. Ekstrak dan verifikasi token sesi server
  const cookies = parseCookies(req.headers?.cookie);
  const authHeader = req.headers?.authorization;
  const token = cookies['spectra_session'] || (authHeader?.startsWith('Bearer ') ? authHeader.slice(7) : null);

  if (!token) {
    return res.status(401).json({ success: false, error: 'Autentikasi diperlukan. Sesi tidak ditemukan.' });
  }

  const session = verifySessionToken(token);
  if (!session) {
    return res.status(401).json({ success: false, error: 'Sesi tidak valid atau telah kedaluwarsa.' });
  }

  // 2. Otorisasi Admin/Authority
  if (session.role !== 'admin' && !session.isAuthority) {
    return res.status(403).json({ success: false, error: 'Akses ditolak. Hanya Administrator yang dapat mereset kredensial pengguna.' });
  }

  // 3. Perlindungan CSRF jika request menggunakan cookie sesi
  if (cookies['spectra_session'] && !validateCsrf(req)) {
    return res.status(403).json({ success: false, error: 'Validasi CSRF Token gagal.' });
  }

  const body = req.body || {};
  const targetUserId = String(body.userId || '').trim();
  let newPassword = String(body.newPassword || '').trim();

  if (!targetUserId) {
    return res.status(400).json({ success: false, error: 'Parameter userId wajib disertakan.' });
  }

  let isAutoGenerated = false;
  if (!newPassword) {
    // Generate secure random temporary password jika tidak diisi admin
    const randomSuffix = crypto.randomBytes(4).toString('hex').toUpperCase();
    newPassword = `Spectra#${randomSuffix}`;
    isAutoGenerated = true;
  } else if (newPassword.length < 6) {
    return res.status(400).json({ success: false, error: 'Password baru minimal 6 karakter.' });
  }

  try {
    const supabase = getSupabaseServerClient();

    // Periksa target user
    const { data: targets, error: targetErr } = await supabase
      .from('system_users')
      .select('id, username, session_version')
      .eq('id', targetUserId)
      .limit(1);

    if (targetErr || !targets || targets.length === 0) {
      return res.status(404).json({ success: false, error: 'Pengguna yang dimaksud tidak ditemukan di sistem.' });
    }

    const targetUser = targets[0];

    // Hash password baru dengan Argon2id
    const newHash = await hashPassword(newPassword);
    const nextSessionVersion = (targetUser.session_version || 1) + 1;

    // Update password_hash, hapus plaintext legacy (password = null), bump session_version
    const { error: updateErr } = await supabase
      .from('system_users')
      .update({
        password_hash: newHash,
        password: null, // Hapus plaintext jika ada
        session_version: nextSessionVersion,
        failed_login_attempts: 0,
        locked_until: null
      })
      .eq('id', targetUserId);

    if (updateErr) {
      throw updateErr;
    }

    // PENTING: DILARANG mengembalikan password hash ke client!
    return res.status(200).json({
      success: true,
      message: `Password pengguna ${targetUser.username} berhasil direset. Sesi lama pengguna telah diinvalidasi.`,
      temporaryPassword: isAutoGenerated ? newPassword : undefined
    });

  } catch (err: any) {
    console.error('[API Admin Reset Password Error]:', err);
    return res.status(500).json({ success: false, error: 'Gagal mereset password pengguna.' });
  }
}

